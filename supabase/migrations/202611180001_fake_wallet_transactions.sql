alter table public.listings
  add column if not exists status text not null default 'active',
  add column if not exists reserved_by uuid references auth.users(id),
  add column if not exists sold_at timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'listings_status_check' and conrelid = 'public.listings'::regclass
  ) then
    alter table public.listings
      add constraint listings_status_check
      check (status in ('active', 'reserved', 'sold'));
  end if;
end;
$$;

create table if not exists public.fake_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance numeric(10, 2) not null default 500.00 check (balance >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.marketplace_transactions (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  seller_id uuid not null references auth.users(id) on delete cascade,
  listing_id bigint not null references public.listings(id) on delete cascade,
  amount numeric(10, 2) not null check (amount >= 0),
  status text not null default 'pending_receipt'
    check (status in ('pending_receipt', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  cancelled_at timestamptz
);

create table if not exists public.seller_ratings (
  id bigint generated by default as identity primary key,
  transaction_id bigint not null unique references public.marketplace_transactions(id) on delete cascade,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  seller_id uuid not null references auth.users(id) on delete cascade,
  rating int not null check (rating between 1 and 5),
  created_at timestamptz not null default now()
);

alter table public.fake_wallets enable row level security;
alter table public.marketplace_transactions enable row level security;
alter table public.seller_ratings enable row level security;

grant select on public.fake_wallets to authenticated;
grant select on public.marketplace_transactions to authenticated;
revoke all on public.seller_ratings from anon, authenticated;
grant select on public.seller_ratings to authenticated, anon;

drop policy if exists "Users read their fake wallet" on public.fake_wallets;
create policy "Users read their fake wallet"
on public.fake_wallets for select to authenticated
using (user_id = auth.uid());

drop policy if exists "Participants read marketplace transactions" on public.marketplace_transactions;
create policy "Participants read marketplace transactions"
on public.marketplace_transactions for select to authenticated
using (buyer_id = auth.uid() or seller_id = auth.uid());

drop policy if exists "Buyers rate completed sellers" on public.seller_ratings;

drop policy if exists "Ratings are public" on public.seller_ratings;
create policy "Ratings are public"
on public.seller_ratings for select to authenticated, anon
using (true);

insert into public.fake_wallets (user_id)
select id from auth.users
on conflict (user_id) do nothing;

create or replace function public.create_fake_wallet()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.fake_wallets (user_id) values (new.id)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists create_fake_wallet_on_signup on auth.users;
create trigger create_fake_wallet_on_signup
after insert on auth.users
for each row execute function public.create_fake_wallet();

create or replace function public.start_purchase(p_listing_id bigint)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_listing public.listings%rowtype;
  v_buyer_balance numeric(10, 2);
  v_transaction_id bigint;
  v_listing_title text;
begin
  select * into v_listing from public.listings where id = p_listing_id for update;
  if not found then raise exception 'Listing not found'; end if;
  if v_listing.status <> 'active' then raise exception 'This listing is no longer available'; end if;
  if v_listing.seller_id = auth.uid() then raise exception 'You cannot buy your own listing'; end if;

  select balance into v_buyer_balance
  from public.fake_wallets where user_id = auth.uid() for update;
  if v_buyer_balance is null then
    insert into public.fake_wallets (user_id) values (auth.uid()) returning balance into v_buyer_balance;
  end if;
  if v_buyer_balance < v_listing.price then raise exception 'Insufficient fake money'; end if;

  update public.fake_wallets
  set balance = balance - v_listing.price, updated_at = now()
  where user_id = auth.uid();

  update public.listings
  set status = 'reserved', reserved_by = auth.uid()
  where id = p_listing_id;

  insert into public.marketplace_transactions (buyer_id, seller_id, listing_id, amount)
  values (auth.uid(), v_listing.seller_id, p_listing_id, v_listing.price)
  returning id into v_transaction_id;

  insert into public.purchases
    (buyer_id, seller_id, listing_id, title, seller_name, amount, status)
  values
    (auth.uid(), v_listing.seller_id, p_listing_id, v_listing.name,
     coalesce((select display_name from public.profiles where id = v_listing.seller_id), 'RPI student'),
     v_listing.price, 'Pending');

  v_listing_title := v_listing.name;
  insert into public.direct_messages (sender_id, recipient_id, body)
  values (
    auth.uid(),
    v_listing.seller_id,
    'Purchase started for "' || v_listing_title ||
    '". I confirmed the demo transaction and will confirm when I receive the item.'
  );

  return json_build_object(
    'transaction_id', v_transaction_id,
    'balance', v_buyer_balance - v_listing.price,
    'seller_id', v_listing.seller_id
  );
end;
$$;

create or replace function public.confirm_receipt(p_transaction_id bigint)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_transaction public.marketplace_transactions%rowtype;
  v_listing_title text;
  v_seller_name text;
begin
  select * into v_transaction
  from public.marketplace_transactions
  where id = p_transaction_id
  for update;
  if not found then raise exception 'Transaction not found'; end if;
  if v_transaction.buyer_id <> auth.uid() then raise exception 'Only the buyer can confirm receipt'; end if;
  if v_transaction.status <> 'pending_receipt' then raise exception 'Transaction is no longer pending'; end if;

  insert into public.fake_wallets (user_id) values (v_transaction.seller_id)
  on conflict (user_id) do nothing;
  update public.fake_wallets
  set balance = balance + v_transaction.amount, updated_at = now()
  where user_id = v_transaction.seller_id;

  update public.marketplace_transactions
  set status = 'completed', completed_at = now()
  where id = p_transaction_id;

  update public.listings
  set status = 'sold', reserved_by = null, sold_at = now()
  where id = v_transaction.listing_id;

  update public.purchases
  set status = 'Completed', purchased_at = now()
  where buyer_id = v_transaction.buyer_id
    and listing_id = v_transaction.listing_id
    and status = 'Pending';

  select name into v_listing_title from public.listings where id = v_transaction.listing_id;
  v_listing_title := coalesce(v_listing_title, 'the item');
  select display_name into v_seller_name from public.profiles where id = v_transaction.seller_id;

  insert into public.direct_messages (sender_id, recipient_id, body)
  values (
    v_transaction.buyer_id,
    v_transaction.seller_id,
    'I confirmed receipt of "' || v_listing_title ||
    '". Payment of $' || v_transaction.amount::text || ' has been released.'
  );

  return json_build_object(
    'transaction_id', p_transaction_id,
    'status', 'completed',
    'seller_id', v_transaction.seller_id,
    'seller_name', coalesce(v_seller_name, 'RPI student')
  );
end;
$$;

create or replace function public.cancel_purchase(p_transaction_id bigint)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_transaction public.marketplace_transactions%rowtype;
  v_listing_title text;
begin
  select * into v_transaction
  from public.marketplace_transactions
  where id = p_transaction_id
  for update;
  if not found then raise exception 'Transaction not found'; end if;
  if v_transaction.buyer_id <> auth.uid() then raise exception 'Only the buyer can cancel'; end if;
  if v_transaction.status <> 'pending_receipt' then raise exception 'Transaction is no longer pending'; end if;

  update public.fake_wallets
  set balance = balance + v_transaction.amount, updated_at = now()
  where user_id = v_transaction.buyer_id;

  select name into v_listing_title from public.listings where id = v_transaction.listing_id;
  v_listing_title := coalesce(v_listing_title, 'the item');

  update public.listings
  set status = 'active', reserved_by = null
  where id = v_transaction.listing_id;

  update public.marketplace_transactions
  set status = 'cancelled', cancelled_at = now()
  where id = p_transaction_id;

  update public.purchases
  set status = 'Cancelled'
  where buyer_id = v_transaction.buyer_id
    and listing_id = v_transaction.listing_id
    and status = 'Pending';

  insert into public.direct_messages (sender_id, recipient_id, body)
  values (
    v_transaction.buyer_id,
    v_transaction.seller_id,
    'I canceled the purchase of "' || v_listing_title ||
    '". The listing has been returned to the marketplace and my demo funds were refunded.'
  );

  insert into public.direct_messages (sender_id, recipient_id, body)
  values (
    v_transaction.seller_id,
    v_transaction.buyer_id,
    'The buyer canceled "' || v_listing_title ||
    '". The item has been placed back on the listings.'
  );

  return json_build_object(
    'transaction_id', p_transaction_id,
    'status', 'cancelled',
    'refund', v_transaction.amount
  );
end;
$$;

create or replace function public.rate_seller(
  p_transaction_id bigint,
  p_seller_id uuid,
  p_rating int
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_transaction public.marketplace_transactions%rowtype;
begin
  if p_rating < 1 or p_rating > 5 then raise exception 'Rating must be between 1 and 5'; end if;
  select * into v_transaction
  from public.marketplace_transactions
  where id = p_transaction_id
  for update;
  if not found then raise exception 'Transaction not found'; end if;
  if v_transaction.buyer_id <> auth.uid() then raise exception 'Only the buyer can rate'; end if;
  if v_transaction.seller_id <> p_seller_id then raise exception 'Seller mismatch'; end if;
  if v_transaction.status <> 'completed' then raise exception 'The transaction must be completed first'; end if;

  insert into public.seller_ratings (transaction_id, buyer_id, seller_id, rating)
  values (p_transaction_id, auth.uid(), p_seller_id, p_rating)
  on conflict (transaction_id) do update set rating = excluded.rating;

  return json_build_object('transaction_id', p_transaction_id, 'rating', p_rating);
end;
$$;

