begin;

create table if not exists public.purchases (
  id bigint generated by default as identity primary key,
  buyer_id uuid not null references auth.users(id) on delete cascade,
  seller_id uuid not null references auth.users(id) on delete cascade,
  listing_id bigint references public.listings(id) on delete set null,
  title text not null,
  seller_name text,
  amount numeric(10, 2) not null check (amount >= 0),
  purchased_at timestamptz not null default now(),
  status text not null default 'Completed'
    check (status in ('Pending', 'Completed', 'Cancelled'))
);

create index if not exists purchases_buyer_purchased_at_idx
  on public.purchases (buyer_id, purchased_at desc);

alter table public.purchases enable row level security;

drop policy if exists "Buyers and sellers read purchases" on public.purchases;
create policy "Buyers and sellers read purchases"
on public.purchases for select to authenticated
using (buyer_id = auth.uid() or seller_id = auth.uid());

drop policy if exists "Buyers create purchases" on public.purchases;
create policy "Buyers create purchases"
on public.purchases for insert to authenticated
with check (buyer_id = auth.uid());

commit;
