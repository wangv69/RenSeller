create table public.listings (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references auth.users(id), name text not null,
  price numeric not null, category text not null, condition text, image_path text
);
-- Deliberately permissive legacy policies must not survive the migration.
alter table public.listings enable row level security;
grant all on public.listings to anon, authenticated;
grant usage on sequence public.listings_id_seq to authenticated;
create policy legacy_access on public.listings for all using (true) with check (true);
grant update (name) on public.listings to authenticated;
