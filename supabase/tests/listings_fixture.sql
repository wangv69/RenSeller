-- Synthetic Supabase auth helpers and the pre-existing listing schema.
-- Used only in a disposable PostgreSQL cluster created by pytest.
create role anon nologin;
create role authenticated nologin;
create schema auth;
create function auth.jwt() returns jsonb language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb;
$$;
create function auth.uid() returns uuid language sql stable as $$
  select (auth.jwt()->>'sub')::uuid;
$$;
grant usage on schema auth to anon, authenticated;
create table auth.users (
  id uuid primary key, email text, raw_app_meta_data jsonb default '{}',
  email_confirmed_at timestamptz default now(), deleted_at timestamptz, banned_until timestamptz
);
